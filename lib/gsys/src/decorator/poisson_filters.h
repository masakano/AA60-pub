inline int32_t load_poisson_coef(int32_t pattern, vec2f_t *buffer)
{
	if (pattern == 32) {
		memcpy(buffer, c_poisson32, sizeof(c_poisson32));
		return sizeof(c_poisson32) / sizeof(vec2f_t);
	}
	if (pattern == 64) {
		memcpy(buffer, c_poisson64, sizeof(c_poisson64));
		return sizeof(c_poisson64) / sizeof(vec2f_t);
	}
	if (pattern == 128) {
		memcpy(buffer, c_poisson128, sizeof(c_poisson128));
		return sizeof(c_poisson128) / sizeof(vec2f_t);
	}
	aux_error(true, "unknown filter pattern [%d] (must be [32:64:128])\n", pattern);
}

